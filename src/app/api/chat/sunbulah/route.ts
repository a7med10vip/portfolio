const genAI = new GoogleGenerativeAI(process.env.GEMINI_API_KEY!);

export async function POST(req: NextRequest) {
  try {
    const body = await req.json();
    const messages = body?.messages;
    if (!Array.isArray(messages) || messages.length === 0 || messages.length > 30) {
      return NextResponse.json({ error: "Invalid messages" }, { status: 400 });
    }

    const clean = messages
      .filter((m: unknown): m is { role: string; content: string } => {
        if (!m || typeof m !== "object") return false;
        const v = m as { role?: unknown; content?: unknown };
        return (v.role === "user" || v.role === "assistant") && typeof v.content === "string";
      })
      .map((m) => ({ ...m, content: m.content.slice(0, 3000) }));

    if (clean.length === 0) {
      return NextResponse.json({ error: "Invalid messages" }, { status: 400 });
    }

    const model = genAI.getGenerativeModel({
      model: "gemini-2.5-flash",
      systemInstruction: SYSTEM_PROMPT,
    });

    const history = clean.slice(0, -1).map((m) => ({
      role: m.role === "assistant" ? "model" : "user",
      parts: [{ text: m.content }],
    }));

    const chat = model.startChat({
      history,
      generationConfig: { temperature: 0.6, maxOutputTokens: 800 },
    });

    const result = await chat.sendMessage(clean[clean.length - 1].content);
    const reply = result.response.text();

    return NextResponse.json({ reply });
  } catch (err) {
    console.error("sunbulah chat error", err);
    return NextResponse.json(
      { reply: "حدث خطأ مؤقت. حاول مرة أخرى، أو راسلني على hello@ahmedali.online" },
      { status: 200 },
    );
  }
}
